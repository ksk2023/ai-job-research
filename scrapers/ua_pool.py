class UAPool:
    """User-Agent 轮换池。"""

    def __init__(self, agents: list[str] | None = None):
        self.agents = agents or USER_AGENTS

    def random(self) -> str:
        """随机返回一个 UA。"""
        return random.choice(self.agents)

    def chrome_only(self) -> str:
        """随机返回一个 Chrome UA（部分站点对非 Chrome 浏览器不友好）。"""
        chrome_agents = [a for a in self.agents if "Chrome" in a and "Edg" not in a]
        return random.choice(chrome_agents)

    def headers(self, extra: dict | None = None) -> dict:
        """返回带随机 UA 的完整请求头。"""
        h = {
            "User-Agent": self.random(),
            "Accept": "text/html,application/xhtml+xml,application/xml;q=0.9,*/*;q=0.8",
            "Accept-Language": "zh-CN,zh;q=0.9,en;q=0.8",
            "Accept-Encoding": "gzip, deflate, br",
            "Connection": "keep-alive",
            "Upgrade-Insecure-Requests": "1",
        }
        if extra:
            h.update(extra)
        return h


